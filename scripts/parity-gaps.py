#!/usr/bin/env python3
"""Write docs/parity/GAPS.md: every row that is not `done`, grouped by dependency layer.

    scripts/parity-gaps.py

Layers follow the build order in docs/parity/PLAN.md: core/state/IPC → backend integration →
pages → settings → polish. Within a layer, sections are listed in build order and rows keep
their matrix order. Rows with Rust code already present (`rust_evidence`) are marked so the
cheapest finishes are visible.
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
P = ROOT / "docs" / "parity"

LAYERS = [
    (
        "1. Core / state / IPC",
        "Gateway client, server→client requests, connection and profile state that every page "
        "depends on. Lives in `hermes-core`, unit-tested without a window.",
        ["APRV", "RMT", "SGTW", "PROF", "MODL", "ONB", "UPD"],
    ),
    (
        "2. Backend integration (chat surface)",
        "The everyday loop: composer, transcript, tool rows, sessions, projects.",
        ["CHAT", "TRNS", "TOOL", "SESS", "PROJ", "PANE"],
    ),
    (
        "3. Pages",
        "Full-page routes and their tabs: Capabilities (skills, tools, MCP, plugins), Messaging, "
        "Artifacts, Scheduled jobs, Memory, Voice, Command center, Starmap, imports.",
        ["SKIL", "TSET", "MCP", "PLUG", "MEM", "MSG", "CRON", "ART", "VOIC", "EXTR"],
    ),
    (
        "4. Settings",
        "Every settings page wired to the same `config.yaml` keys, persisted, and live where the "
        "original is live.",
        [
            "SET", "SMOD", "SCHT", "SAPP", "SWRK", "SSAF", "SBRW", "SMEM", "SVOI", "SADV",
            "SGTW", "SKEY", "SNOT", "SSES", "SVLT", "SPRV", "SPLG", "SBIL", "SABT",
        ],
    ),
    (
        "5. Polish",
        "Shortcuts and palette, themes, notifications, window chrome, tray, HUD, pet.",
        ["KEYS", "THEM", "NOTI", "WIN"],
    ),
]


def main() -> None:
    items = json.loads((P / "items.json").read_text())
    ann: dict = {}
    for f in sorted((P / "annotations").glob("*.json")):
        for k, v in json.loads(f.read_text()).items():
            if not k.startswith("_"):
                ann.setdefault(k, {}).update(v)
    by_code: dict[str, list[dict]] = {}
    for it in items:
        by_code.setdefault(it["id"].split("-")[0], []).append(it)
    seen = {c for _, _, codes in LAYERS for c in codes}
    # SGTW is a settings page but also the connection layer; list it once, under core.
    missing_codes = set(by_code) - seen
    assert not missing_codes, f"unassigned sections: {missing_codes}"

    open_total = sum(1 for it in items if it["status"] not in ("done", "unsupported"))
    out = [
        "# Parity gap list",
        "",
        "Generated by `scripts/parity-gaps.py` from `docs/parity/items.json` + annotations. "
        "Ordered by dependency: build a layer's rows before the layers that use them.",
        "",
        f"**{open_total} open rows** (missing + partial) of {len(items)}. "
        "`code` = the Rust repo already has related code (`rust_evidence`), "
        "usually the cheapest to finish.",
        "",
        "| Layer | Open | Partial | With Rust code |",
        "|---|---:|---:|---:|",
    ]
    body: list[str] = []
    for title, blurb, codes in LAYERS:
        rows = [
            it
            for c in codes
            for it in by_code.get(c, [])
            if it["status"] not in ("done", "unsupported")
        ]
        partial = sum(1 for it in rows if it["status"] == "partial")
        withcode = sum(1 for it in rows if ann.get(it["id"], {}).get("rust_evidence"))
        out.append(f"| {title} | {len(rows)} | {partial} | {withcode} |")
        body += ["", f"## {title}", "", blurb, ""]
        for c in codes:
            sec = [it for it in by_code.get(c, []) if it["status"] not in ("done", "unsupported")]
            if not sec:
                continue
            done = sum(1 for it in by_code[c] if it["status"] == "done")
            body.append(
                f"### {c}: {by_code[c][0]['section']} ({len(sec)} open, {done} done of {len(by_code[c])})"
            )
            body.append("")
            for it in sec:
                a = ann.get(it["id"], {})
                tags = [it["status"]]
                if a.get("rust_evidence"):
                    tags.append("code")
                body.append(f"- `{it['id']}` {it['feature']} — {', '.join(tags)}")
            body.append("")
    (P / "GAPS.md").write_text("\n".join(out + body).rstrip() + "\n")
    print(f"{open_total} open rows -> docs/parity/GAPS.md")


if __name__ == "__main__":
    main()
